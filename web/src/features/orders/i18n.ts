export function orderLabel(locale: Locale, key: OrderMessageKey): string {
  return orderMessages[locale][key] ?? en[key];
}
export function orderStatusLabel(locale: Locale, status: number): string {
  const key = status === 1 ? 'statusPending' :
    status === 2 ? 'statusPaid' : status === 3 ? 'statusExpired' :
    status === 4 ? 'statusSelecting' : undefined;
  return key ? orderLabel(locale, key) : String(status);
}
